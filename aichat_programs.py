"""Casio BASIC programs for the calculator side of AI chat.

AICHAT  shows the latest answer (Prog "AIANS"), then asks for a question into Str 1.
AIANS   generated by the Mac for every answer: clears Str 1, then shows the answer
        page by page (7 lines + a footer, EXE to continue).
"""

from casio_basic import program_file, wrap

MAIN_NAME = "AICHAT"
ANSWER_NAME = "AIANS"
LINES_PER_PAGE = 7
BLANK_QUESTION = " "

AICHAT_SOURCE = r'''
\ClrText
\Prog "AIANS"
\ClrText
"=== AI CHAT ==="
"Type question, EXE"
"(AC/ON to quit)"
?\->\Str 1
\ClrText
"Question saved."
" "
"Now MENU > LINK"
"> F2 (RECV)."
"When it says done,"
"run AICHAT again."
'''

WELCOME_TEXT = (
    "AI CHAT is ready.\n\n"
    "Type a question and press EXE, then go to LINK > RECV. "
    "The Mac reads it, asks the AI and sends the answer back. "
    "Run AICHAT again to read it.\n\n"
    "Type NEW to start a fresh conversation."
)


def literal(line):
    return '"%s"' % (line or " ")


def answer_source(text):
    lines = wrap(text)
    pages = [lines[i:i + LINES_PER_PAGE] for i in range(0, len(lines), LINES_PER_PAGE)] or [[]]
    src = ['"%s"\\->\\Str 1' % BLANK_QUESTION]
    for n, page in enumerate(pages, 1):
        src.append("\\ClrText")
        src.extend(literal(line) for line in page)
        src.append(literal("[EXE] %d/%d" % (n, len(pages))) + "\\Disp")
    return "\n".join(src)


def main_program():
    return program_file(AICHAT_SOURCE)


def answer_program(text):
    return program_file(answer_source(text))
